//! Regen evaluator — decides whether `caro run` / `caro generate` should use
//! the cached lock, regenerate the lock entirely, or merely create an
//! exploratory challenger variant alongside the existing active one.
//!
//! Inputs (from PR-6 onward also include track-record stats and the runtime
//! journal): the parsed AST's intent hash, the lock's per-variant model /
//! caro-version / tool-versions, the current platform, and a set of mode
//! flags from the CLI (`--use-cached` / `--explore`).

use crate::caroml::ast::Task;
use crate::caroml::lock::Lock;
use sha2::{Digest, Sha256};

/// What the runtime should do for this invocation.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Decision {
    /// The existing active variant is fresh; use it.
    UseCache,
    /// Must regenerate before running. Carries human-readable reasons.
    HardRegen { reasons: Vec<String> },
    /// Cache is fine, but produce a challenger variant in parallel
    /// (only effective when `--explore` is set; otherwise treated as UseCache).
    SoftExplore { reasons: Vec<String> },
}

impl Decision {
    pub fn is_use_cache(&self) -> bool {
        matches!(self, Self::UseCache)
    }

    pub fn is_hard_regen(&self) -> bool {
        matches!(self, Self::HardRegen { .. })
    }

    /// Human-readable reasons attached to the decision (empty for UseCache).
    pub fn reasons(&self) -> &[String] {
        match self {
            Self::UseCache => &[],
            Self::HardRegen { reasons } | Self::SoftExplore { reasons } => reasons.as_slice(),
        }
    }
}

/// Mode flags that influence the decision.
#[derive(Debug, Clone, Copy, Default)]
pub struct Mode {
    /// Skip all evaluation; force HardRegen (used by `caro upgrade`).
    pub force_regen: bool,
    /// Suppress all SoftExplore signals; cache is used unless HardRegen fires.
    /// (Used by `caro run --use-cached`.)
    pub use_cached: bool,
    /// Promote SoftExplore signals to actually generate a challenger.
    /// (Used by `caro run --explore`.)
    pub explore: bool,
}

/// Inputs the evaluator needs (so callers don't have to wire 6 args).
pub struct EvalInput<'a> {
    pub task: &'a Task,
    pub lock: Option<&'a Lock>,
    pub platform: &'a str,
    pub current_caro_version: &'a str,
    pub current_model: &'a str,
    pub current_backend: &'a str,
    pub mode: Mode,
}

/// Decide what action to take.
pub fn decide(input: &EvalInput<'_>) -> Decision {
    if input.mode.force_regen {
        return Decision::HardRegen {
            reasons: vec!["force_regen requested".into()],
        };
    }

    let lock = match input.lock {
        Some(l) => l,
        None => {
            return Decision::HardRegen {
                reasons: vec!["no lock file present".into()],
            };
        }
    };

    // Hard regen: intent_hash mismatch
    let computed_intent_hash = intent_hash(input.task);
    if lock.meta.intent_hash != computed_intent_hash {
        return Decision::HardRegen {
            reasons: vec![format!(
                "intent_hash mismatch (lock: {}, computed: {})",
                short_hash(&lock.meta.intent_hash),
                short_hash(&computed_intent_hash),
            )],
        };
    }

    // Hard regen: no active variant for this platform
    let has_platform = lock
        .steps
        .iter()
        .all(|s| s.active_variant(input.platform).is_some());
    if !has_platform || lock.steps.is_empty() {
        return Decision::HardRegen {
            reasons: vec![format!(
                "no active variant for platform `{}` on every step",
                input.platform
            )],
        };
    }

    if input.mode.use_cached {
        return Decision::UseCache;
    }

    // Soft explore: model / backend / caro_version drift on the active variant
    let mut soft: Vec<String> = Vec::new();
    for step in &lock.steps {
        if let Some(v) = step.active_variant(input.platform) {
            if v.model != input.current_model {
                soft.push(format!(
                    "step {}: variant generated by model `{}`, current is `{}`",
                    step.line, v.model, input.current_model
                ));
                break;
            }
            if v.backend != input.current_backend {
                soft.push(format!(
                    "step {}: variant generated by backend `{}`, current is `{}`",
                    step.line, v.backend, input.current_backend
                ));
                break;
            }
        }
    }
    if lock.meta.caro_version != input.current_caro_version {
        soft.push(format!(
            "lock written by caro {}, current is {}",
            lock.meta.caro_version, input.current_caro_version
        ));
    }

    if soft.is_empty() {
        Decision::UseCache
    } else if input.mode.explore {
        Decision::SoftExplore { reasons: soft }
    } else {
        // Reasons for re-generation exist but explore wasn't requested;
        // surface them via UseCache — the reasons are still visible in `caro why`.
        Decision::UseCache
    }
}

