/// SHA-256 hex digest of the parsed-and-normalized AST. v0.1 normalization
/// is minimal: title + why + needs + platform_pragmas + params + each
/// step's `intent` (post-LET-substitution). `notes` are intentionally
/// excluded so refining a hint to the LLM doesn't invalidate the lock.
pub fn intent_hash(task: &Task) -> String {
    let mut h = Sha256::new();
    h.update(b"TASK:");
    h.update(task.title.as_bytes());
    h.update(b"\nWHY:");
    if let Some(why) = &task.why {
        h.update(why.as_bytes());
    }
    h.update(b"\nNEED:");
    for need in &task.needs {
        h.update(need.as_bytes());
        h.update(b",");
    }
    h.update(b"\nON:");
    for p in &task.platform_pragmas {
        h.update(p.platform.as_bytes());
        h.update(b"|prefer=");
        for x in &p.prefer {
            h.update(x.as_bytes());
            h.update(b",");
        }
        h.update(b"|avoid=");
        for x in &p.avoid {
            h.update(x.as_bytes());
            h.update(b",");
        }
        h.update(b";");
    }
    h.update(b"\nLET:");
    for p in &task.params {
        h.update(p.name.as_bytes());
        h.update(b"=");
        h.update(p.value.as_bytes());
        h.update(b";");
    }
    h.update(b"\nDO:");
    for step in &task.steps {
        h.update(step.intent.as_bytes());
        h.update(b"\n");
    }
    format!("sha256:{}", hex_encode(&h.finalize()))
}

fn hex_encode(bytes: &[u8]) -> String {
    let mut s = String::with_capacity(bytes.len() * 2);
    for b in bytes {
        s.push(hex_nibble(b >> 4));
        s.push(hex_nibble(b & 0x0f));
    }
    s
}

fn hex_nibble(n: u8) -> char {
    match n {
        0..=9 => (b'0' + n) as char,
        _ => (b'a' + n - 10) as char,
    }
}

fn short_hash(s: &str) -> String {
    s.chars().take(15).collect()
}

