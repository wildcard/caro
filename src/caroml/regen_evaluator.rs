#[cfg(test)]
mod tests {
    use super::*;
    use crate::caroml::ast::{Param, PlatformPragma, Step, Task};
    use crate::caroml::lock::{Lock, Meta, Step as LockStep, Variant};
    use chrono::Utc;
    use std::collections::BTreeMap;

    fn sample_task() -> Task {
        Task {
            source_path: None,
            title: "demo".into(),
            why: Some("for tests".into()),
            needs: vec!["sudo".into()],
            platform_pragmas: vec![PlatformPragma {
                platform: "macos".into(),
                prefer: vec!["bsd-tools".into()],
                avoid: vec![],
            }],
            params: vec![Param {
                name: "p".into(),
                value: "/tmp".into(),
            }],
            steps: vec![Step {
                line: 5,
                intent: "do something".into(),
                raw_intent: "do something".into(),
                notes: vec![],
            }],
        }
    }

    fn sample_lock(intent_hash: &str) -> Lock {
        let mut lock = Lock::default();
        lock.meta = Meta {
            caro_version: "1.4.0".into(),
            intent_path: "tasks/demo.caro".into(),
            intent_hash: intent_hash.into(),
            supported_platforms: vec!["macos".into()],
            last_full_regen: Some(Utc::now()),
        };
        lock.steps = vec![LockStep {
            line: 5,
            intent: "do something".into(),
            intent_hash: "sha256:step".into(),
            notes: vec![],
            variants: vec![Variant {
                platform: "macos".into(),
                active: true,
                generation_id: "gen_a".into(),
                command: "ls".into(),
                reasoning: "test".into(),
                exports: vec![],
                imports: vec![],
                risk_level: "safe".into(),
                matched_patterns: vec![],
                warnings: vec![],
                confidence: 0.9,
                iterations: 1,
                validations: vec![],
                generated_at: Utc::now(),
                model: "smollm-1.7b".into(),
                backend: "embedded".into(),
                tool_versions: BTreeMap::new(),
                track_record: Default::default(),
                retired_at: None,
            }],
        }];
        lock
    }

    fn input<'a>(task: &'a Task, lock: Option<&'a Lock>, mode: Mode) -> EvalInput<'a> {
        EvalInput {
            task,
            lock,
            platform: "macos",
            current_caro_version: "1.4.0",
            current_model: "smollm-1.7b",
            current_backend: "embedded",
            mode,
        }
    }

    #[test]
    fn intent_hash_is_deterministic() {
        let a = intent_hash(&sample_task());
        let b = intent_hash(&sample_task());
        assert_eq!(a, b);
        assert!(a.starts_with("sha256:"));
    }

    #[test]
    fn intent_hash_changes_when_intent_changes() {
        let mut t1 = sample_task();
        let mut t2 = sample_task();
        t2.steps[0].intent = "do something else".into();
        assert_ne!(intent_hash(&t1), intent_hash(&t2));
        // notes don't affect hash:
        t1.steps[0].notes = vec!["a hint".into()];
        assert_eq!(intent_hash(&t1), intent_hash(&sample_task()));
    }

    #[test]
    fn no_lock_means_hard_regen() {
        let task = sample_task();
        let d = decide(&input(&task, None, Mode::default()));
        assert!(d.is_hard_regen());
    }

    #[test]
    fn intent_hash_mismatch_means_hard_regen() {
        let task = sample_task();
        let lock = sample_lock("sha256:wrong");
        let d = decide(&input(&task, Some(&lock), Mode::default()));
        assert!(d.is_hard_regen());
        assert!(d
            .reasons()
            .iter()
            .any(|r| r.contains("intent_hash mismatch")));
    }

    #[test]
    fn matching_intent_hash_means_use_cache() {
        let task = sample_task();
        let h = intent_hash(&task);
        let lock = sample_lock(&h);
        let d = decide(&input(&task, Some(&lock), Mode::default()));
        assert_eq!(d, Decision::UseCache);
    }

    #[test]
    fn force_regen_overrides_everything() {
        let task = sample_task();
        let h = intent_hash(&task);
        let lock = sample_lock(&h);
        let mode = Mode {
            force_regen: true,
            ..Mode::default()
        };
        let d = decide(&input(&task, Some(&lock), mode));
        assert!(d.is_hard_regen());
    }

    #[test]
    fn missing_platform_variant_means_hard_regen() {
        let task = sample_task();
        let h = intent_hash(&task);
        let lock = sample_lock(&h);
        let mut input_l = input(&task, Some(&lock), Mode::default());
        input_l.platform = "linux";
        let d = decide(&input_l);
        assert!(d.is_hard_regen());
        assert!(d
            .reasons()
            .iter()
            .any(|r| r.contains("no active variant for platform `linux`")));
    }

    #[test]
    fn model_drift_with_explore_yields_soft_explore() {
        let task = sample_task();
        let h = intent_hash(&task);
        let lock = sample_lock(&h);
        let mut input_l = input(&task, Some(&lock), Mode::default());
        input_l.current_model = "smollm-3.0b";
        input_l.mode.explore = true;
        let d = decide(&input_l);
        assert!(matches!(d, Decision::SoftExplore { .. }));
        assert!(d.reasons().iter().any(|r| r.contains("smollm-1.7b")));
    }

    #[test]
    fn model_drift_without_explore_still_use_cache() {
        let task = sample_task();
        let h = intent_hash(&task);
        let lock = sample_lock(&h);
        let mut input_l = input(&task, Some(&lock), Mode::default());
        input_l.current_model = "smollm-3.0b";
        // mode.explore = false (default)
        let d = decide(&input_l);
        assert_eq!(d, Decision::UseCache);
    }

    #[test]
    fn use_cached_mode_suppresses_soft_explore() {
        let task = sample_task();
        let h = intent_hash(&task);
        let lock = sample_lock(&h);
        let mut input_l = input(&task, Some(&lock), Mode::default());
        input_l.current_model = "smollm-3.0b";
        input_l.mode.explore = true;
        input_l.mode.use_cached = true;
        let d = decide(&input_l);
        assert_eq!(d, Decision::UseCache);
    }
}
